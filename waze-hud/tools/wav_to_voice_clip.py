#!/usr/bin/env python3
"""Convert a WAV recording into the embedded overspeed voice clip.

Usage:
    python tools/wav_to_voice_clip.py recording.wav [--start SECONDS] [--end SECONDS]

--start/--end keep only that part of the recording (e.g. a single phrase out
of a file that repeats it).

Accepts 16-bit PCM WAV (mono or stereo, any sample rate). The clip is mixed to
mono, resampled to 16 kHz, trimmed of leading/trailing silence, peak-normalised
and written to main/audio/overspeed_voice.cpp. Standard library only.

Then enable CONFIG_WAZE_HUD_AUDIO_USE_VOICE (menuconfig -> Waze HUD firmware)
or add it to sdkconfig.es3c28p.defaults and rebuild.
"""

from __future__ import annotations

from array import array
from pathlib import Path
import sys
import wave

TARGET_RATE = 16000
MAX_SECONDS = 6.0
PEAK = 0.9
SILENCE_THRESHOLD = 0.02

OUTPUT = Path(__file__).resolve().parents[1] / "main" / "audio" / "overspeed_voice.cpp"


def read_mono(path: Path) -> tuple[list[float], int]:
    with wave.open(str(path), "rb") as wav:
        if wav.getsampwidth() != 2:
            raise SystemExit("WAV must be 16-bit PCM (export as 'WAV 16-bit' in Audacity).")
        channels, rate, frames = wav.getnchannels(), wav.getframerate(), wav.getnframes()
        raw = array("h")
        raw.frombytes(wav.readframes(frames))
        if sys.byteorder == "big":
            raw.byteswap()
    mono = [
        sum(raw[i * channels + c] for c in range(channels)) / channels / 32768.0
        for i in range(frames)
    ]
    return mono, rate


def resample(samples: list[float], rate: int) -> list[float]:
    if rate == TARGET_RATE or not samples:
        return samples
    count = int(len(samples) * TARGET_RATE / rate)
    out = []
    for i in range(count):
        position = i * rate / TARGET_RATE
        left = int(position)
        right = min(left + 1, len(samples) - 1)
        fraction = position - left
        out.append(samples[left] * (1.0 - fraction) + samples[right] * fraction)
    return out


def trim(samples: list[float]) -> list[float]:
    voiced = [i for i, value in enumerate(samples) if abs(value) > SILENCE_THRESHOLD]
    if not voiced:
        raise SystemExit("The recording is silent.")
    margin = int(0.05 * TARGET_RATE)
    return samples[max(0, voiced[0] - margin): voiced[-1] + margin]


def main() -> None:
    args = sys.argv[1:]
    start = end = None
    for flag in ("--start", "--end"):
        if flag in args:
            index = args.index(flag)
            value = float(args[index + 1])
            del args[index:index + 2]
            if flag == "--start":
                start = value
            else:
                end = value
    if len(args) != 1:
        raise SystemExit(__doc__)
    samples, rate = read_mono(Path(args[0]))
    if start is not None or end is not None:
        samples = samples[int((start or 0.0) * rate): int(end * rate) if end is not None else None]
    samples = trim(resample(samples, rate))
    if len(samples) > MAX_SECONDS * TARGET_RATE:
        raise SystemExit(f"Clip is longer than {MAX_SECONDS:.0f} s; record a shorter phrase.")
    peak = max(abs(value) for value in samples) or 1.0
    gain = PEAK / peak
    pcm = [int(round(max(-1.0, min(1.0, value * gain)) * 32767)) for value in samples]

    rows = []
    for start in range(0, len(pcm), 16):
        rows.append("    " + ",".join(str(value) for value in pcm[start:start + 16]))
    source = (
        "// Generated by tools/wav_to_voice_clip.py. Do not edit manually.\n"
        '#include "audio/overspeed_voice.h"\n\n'
        "namespace waze_hud {\n\n"
        "const int16_t kOverspeedVoice[] = {\n" + ",\n".join(rows) + "\n};\n"
        f"const std::size_t kOverspeedVoiceSamples = {len(pcm)};\n\n"
        "}  // namespace waze_hud\n"
    )
    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT} ({len(pcm)} samples, {len(pcm) / TARGET_RATE:.2f} s)")


if __name__ == "__main__":
    main()
